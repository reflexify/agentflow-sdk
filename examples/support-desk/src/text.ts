export type TextKey = keyof (typeof TEXT)['en'];

export function t(lang: Lang, key: TextKey, vars: Record<string, string | number> = {}): string {
  return TEXT[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}
