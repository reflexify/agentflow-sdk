import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { copyApp } from "./app-fixture.js";
import { runCli } from "./http-stub.js";

async function built(): Promise<string> {
  const app = copyApp();
  expect((await runCli(app, ["build"])).code).toBe(0);
  return app;
}

const generated = (app: string) => path.join(app, "src/generated/app.ts");

describe("types", () => {
  it("writes src/generated/app.ts, and --check then passes", async () => {
    const app = await built();
    const out = await runCli(app, ["types"]);
    expect(out).toMatchObject({ code: 0, stdout: "wrote src/generated/app.ts\n" });
    expect(fs.readFileSync(generated(app), "utf8")).toMatch(/^\/\/ Generated by `agentflow-app types` from rfx\/mini 1\.0\.0\./);
    expect(await runCli(app, ["types", "--check"])).toMatchObject({ code: 0 });
    expect(JSON.parse((await runCli(app, ["types", "--json"])).stdout)).toEqual({ file: "src/generated/app.ts", changed: false });
  });

  it("--json prints the file and whether it changed", async () => {
    const app = await built();
    const out = await runCli(app, ["types", "--json"]);
    expect(out.code).toBe(0);
    expect(JSON.parse(out.stdout)).toEqual({ file: "src/generated/app.ts", changed: true });
  });

  it("--check refuses an edited file with TYPES_STALE and writes nothing", async () => {
    const app = await built();
    await runCli(app, ["types"]);
    fs.appendFileSync(generated(app), "// mine\n");
    const edited = fs.readFileSync(generated(app), "utf8");
    const out = await runCli(app, ["types", "--check"]);
    expect(out.code).toBe(1);
    expect(out.stderr).toMatch(/^TYPES_STALE: src\/generated\/app\.ts /);
    expect(fs.readFileSync(generated(app), "utf8")).toBe(edited);
    const json = await runCli(app, ["types", "--check", "--json"]);
    expect(JSON.parse(json.stdout).error).toMatchObject({ code: "TYPES_STALE", files: ["src/generated/app.ts"] });
  });

  it("--check refuses a missing file with TYPES_STALE", async () => {
    const app = await built();
    const out = await runCli(app, ["types", "--check"]);
    expect(out.code).toBe(1);
    expect(out.stderr).toContain("TYPES_STALE");
    expect(fs.existsSync(generated(app))).toBe(false);
  });

  it("--out writes elsewhere", async () => {
    const app = await built();
    const out = await runCli(app, ["types", "--out", "types/app.ts", "--json"]);
    expect(JSON.parse(out.stdout)).toEqual({ file: "types/app.ts", changed: true });
    expect(fs.existsSync(path.join(app, "types/app.ts"))).toBe(true);
  });

  it("refuses with PACKAGE_MISSING when there is no package/", async () => {
    const app = copyApp();
    fs.rmSync(path.join(app, "package"), { recursive: true, force: true });
    const out = await runCli(app, ["types"]);
    expect(out.code).toBe(1);
    expect(out.stderr).toMatch(/^PACKAGE_MISSING: /);
  });
});
