import { describe, expect, it } from "vitest";
import { CliError } from "../src/errors.js";
import { generateTypes } from "../src/types/generate.js";

const manifest = {
  id: "acme/cases",
  version: "1.2.0",
  objects: [
    { key: "workflow:open_case", kind: "workflow" },
    { key: "entity:case", kind: "entity" },
    { key: "entity_field:case/title", kind: "entity_field" },
    { key: "entity_field:case/status", kind: "entity_field" },
    { key: "entity_field:case/old_ref", kind: "entity_field" },
    { key: "entity:legacy", kind: "entity" },
    { key: "trigger:on_open", kind: "trigger" },
    { key: "dashboard:overview", kind: "dashboard" },
    { key: "client:portal", kind: "client" },
    { key: "agent:triage", kind: "agent" },
    { key: "skill:refunds", kind: "skill" },
  ],
};

const bodies: [string, unknown][] = [
  [
    "entity:case",
    {
      name: "Case",
      fields: ["@obj:entity_field:case/title", "@obj:entity_field:case/status", "@obj:entity_field:case/old_ref"],
    },
  ],
  ["entity:legacy", { name: "Legacy", deprecated: true }],
  ["trigger:on_open", { name: "On open" }],
  ["dashboard:overview", { name: "Overview" }],
  ["client:portal", { name: "Portal" }],
  ["agent:triage", { name: "Triage" }],
  ["skill:refunds", { name: "Refunds" }],
  ["entity_field:case/title", { label: "Title", type: "text" }],
  ["entity_field:case/status", { label: "Status", type: "enum", enum_values: [{ value: "open" }, { value: "closed" }] }],
  ["entity_field:case/old_ref", { label: "Old ref", type: "text", deprecated: true }],
  [
    "workflow:open_case",
    {
      name: "Open a case",
      inputSchema: { type: "object", properties: { title: { type: "string" }, urgent: { type: "boolean" } }, required: ["title"] },
    },
  ],
];

const EXPECTED = `// Generated by \`agentflow-app types\` from acme/cases 1.2.0. Do not edit; run \`agentflow-app types\` again.
// Agents and skills are not listed: \`getAppObjects\` never answers for them. A dashboard, a trigger or a
// client has no contract, so its \`contractVersion\` is null and \`satisfies\` is false for it.

export const PACKAGE = { id: 'acme/cases', version: '1.2.0' } as const;

/** Every object of the package, with the version of the contract this code was written against. */
export const OBJECTS = {
  'client:portal': { kind: 'client', contractVersion: null },
  'dashboard:overview': { kind: 'dashboard', contractVersion: null },
  'entity:case': { kind: 'entity', contractVersion: '1.2.0' },
  /** @deprecated */
  'entity:legacy': { kind: 'entity', contractVersion: '1.2.0' },
  /** @deprecated */
  'entity_field:case/old_ref': { kind: 'entity_field', contractVersion: '1.2.0' },
  'entity_field:case/status': { kind: 'entity_field', contractVersion: '1.2.0' },
  'entity_field:case/title': { kind: 'entity_field', contractVersion: '1.2.0' },
  'trigger:on_open': { kind: 'trigger', contractVersion: null },
  'workflow:open_case': { kind: 'workflow', contractVersion: '1.2.0' },
} as const;

export type LogicalKey = keyof typeof OBJECTS;
export type EntityKey = 'case' | 'legacy';
export type WorkflowKey = 'open_case';

/** The value of each field of each entity, as a record carries it. */
export interface EntityFields {
  case: {
    /** @deprecated */
    old_ref?: string | null;
    status?: 'open' | 'closed' | null;
    title?: string | null;
  };
  /** @deprecated */
  legacy: {};
}

/** What starting each workflow takes. */
export interface WorkflowInputs {
  open_case: {
    title: string;
    urgent?: boolean;
  };
}
`;

describe("generateTypes", () => {
  it("writes the package's keys, field values and workflow inputs", () => {
    expect(generateTypes(manifest, new Map(bodies))).toBe(EXPECTED);
  });

  it("says memory types and relationships are left out when the package has them", () => {
    const withMemory = {
      ...manifest,
      objects: [...manifest.objects, { key: "memory_type:known_issue", kind: "memory_type" }, { key: "memory_relationship:affects", kind: "memory_relationship" }],
    };
    const text = generateTypes(withMemory, new Map(bodies));
    expect(text.split("\n").slice(1, 4).join("\n")).toBe(
      "// Agents, skills, memory types and memory relationships are not listed: `getAppObjects` never answers for\n" +
        "// them. A dashboard, a trigger or a client has no contract, so its `contractVersion` is null and `satisfies`\n" +
        "// is false for it.",
    );
    expect(text).not.toContain("memory_type:known_issue");
    expect(text.split("\n").slice(4).join("\n")).toBe(EXPECTED.split("\n").slice(3).join("\n"));
  });

  it("the output does not depend on the order of the files", () => {
    const reversed = new Map([...bodies].reverse());
    const shuffled = { ...manifest, objects: [...manifest.objects].reverse() };
    expect(generateTypes(shuffled, reversed)).toBe(EXPECTED);
  });

  it("a manifest object with no body is refused", () => {
    const objects = new Map(bodies.filter(([key]) => key !== "entity_field:case/status"));
    let error: unknown;
    try {
      generateTypes(manifest, objects);
    } catch (caught) {
      error = caught;
    }
    expect(error).toBeInstanceOf(CliError);
    expect(error).toMatchObject({ code: "PACKAGE_MISSING", message: expect.stringContaining("entity_field:case/status") });
  });

  it("types each field type a record carries", () => {
    const types: [string, Record<string, unknown>, string][] = [
      ["a_text", { type: "text" }, "string"],
      ["b_number", { type: "number" }, "number"],
      ["c_boolean", { type: "boolean" }, "boolean"],
      ["d_date", { type: "date" }, "string"],
      ["e_datetime", { type: "datetime" }, "string"],
      ["f_multi", { type: "multi_select", enum_values: [{ value: "x" }, { value: "y" }] }, "('x' | 'y')[]"],
      ["g_file", { type: "file" }, "unknown"],
      ["h_reference", { type: "reference" }, "string"],
      ["i_references", { type: "reference_list" }, "string[]"],
      ["j_formula", { type: "formula", formula_result_type: "number" }, "number"],
      ["k_code", { type: "auto_number", auto_number_format: "C-{{ value }}" }, "string"],
      ["l_counter", { type: "auto_number" }, "number"],
      ["m_list", { type: "list" }, "unknown"],
      ["n_new", { type: "hologram" }, "unknown"],
    ];
    const objects = new Map<string, unknown>([["entity:t", { fields: types.map(([key]) => `@obj:entity_field:t/${key}`) }]]);
    for (const [key, body] of types) objects.set(`entity_field:t/${key}`, body);
    const pkg = {
      id: "acme/t",
      version: "0.1.0",
      objects: [{ key: "entity:t", kind: "entity" }, ...types.map(([key]) => ({ key: `entity_field:t/${key}`, kind: "entity_field" }))],
    };
    const text = generateTypes(pkg, objects);
    for (const [key, , ts] of types) expect(text).toContain(`    ${key}?: ${ts === "unknown" ? ts : `${ts} | null`};\n`);
  });

  it("gives a workflow without an input schema no inputs, quotes a key that is not an identifier and marks a deprecated workflow", () => {
    const pkg = {
      id: "acme/w",
      version: "2.0.0",
      objects: [
        { key: "workflow:plain", kind: "workflow" },
        { key: "workflow:old-one", kind: "workflow" },
      ],
    };
    const objects = new Map<string, unknown>([
      ["workflow:plain", { inputSchema: null }],
      ["workflow:old-one", { deprecated: true }],
    ]);
    expect(generateTypes(pkg, objects)).toContain(
      "export interface WorkflowInputs {\n  /** @deprecated */\n  'old-one': Record<string, never>;\n  plain: Record<string, never>;\n}\n",
    );
    expect(generateTypes(pkg, objects)).toContain("export type EntityKey = never;\nexport type WorkflowKey = 'old-one' | 'plain';\n");
    expect(generateTypes(pkg, objects)).toContain("export interface EntityFields {}\n");
  });
});
