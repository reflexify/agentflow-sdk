export function chatLocale(lang: string | null, browser: readonly string[], offered: readonly ChatLanguage[]): ChatLanguage {
  for (const tag of [lang, ...browser]) {
    const primary = tag?.trim().toLowerCase().split('-')[0];
    const hit = offered.find((language) => language === primary);
    if (hit) return hit;
  }
  return offered[0] ?? 'en';
}
